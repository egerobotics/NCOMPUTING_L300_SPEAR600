/* RGB565 color */
static unsigned short rgb565(int r, int g, int b) {
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
}

static void put_pixel(int x, int y, unsigned short color) {
    if (x >= 0 && x < xres && y >= 0 && y < yres)
        fb_mem[y * (line_len/2) + x] = color;
}

static void fill_rect(int x, int y, int w, int h, unsigned short color) {
    int i, j;
    for (j = y; j < y + h && j < yres; j++)
        for (i = x; i < x + w && i < xres; i++)
            put_pixel(i, j, color);
}

static void draw_char(int x, int y, char c, unsigned short fg, unsigned short bg, int scale) {
    int i, j, si, sj;
    const unsigned char *glyph;
    if (c < 32 || c > 127) c = '?';
    glyph = font8x8[(int)c];
    for (j = 0; j < 8; j++)
        for (i = 0; i < 8; i++) {
            unsigned short color = (glyph[j] & (0x80 >> i)) ? fg : bg;
            for (sj = 0; sj < scale; sj++)
                for (si = 0; si < scale; si++)
                    put_pixel(x + i*scale + si, y + j*scale + sj, color);
        }
}

static void draw_string(int x, int y, const char *s, unsigned short fg, unsigned short bg, int scale) {
    while (*s) {
        draw_char(x, y, *s, fg, bg, scale);
        x += 8 * scale;
        s++;
    }
}

static void read_line(const char *path, char *buf, int len) {
    FILE *f = fopen(path, "r");
    buf[0] = 0;
    if (f) { fgets(buf, len, f); fclose(f); }
    buf[strcspn(buf, "\n")] = 0;
}

int main(void) {
    struct fb_var_screeninfo vinfo;
    struct fb_fix_screeninfo finfo;
    char buf[256], uptime[64], mem[64], ip[64];
    unsigned short bg, title_bg, text_fg, accent;
    FILE *f;
    int y;

    fb_fd = open("/dev/fb0", O_RDWR);
    if (fb_fd < 0) { perror("open /dev/fb0"); return 1; }

    ioctl(fb_fd, FBIOGET_FSCREENINFO, &finfo);
    ioctl(fb_fd, FBIOGET_VSCREENINFO, &vinfo);

    xres = vinfo.xres;
    yres = vinfo.yres;
    bpp = vinfo.bits_per_pixel;
    line_len = finfo.line_length;

    fb_mem = mmap(0, finfo.smem_len, PROT_READ|PROT_WRITE, MAP_SHARED, fb_fd, 0);
    if (fb_mem == (void*)-1) { perror("mmap"); return 1; }

    /* Colors */
    bg = rgb565(32, 32, 48);
    title_bg = rgb565(0, 100, 180);
    text_fg = rgb565(220, 220, 220);
    accent = rgb565(0, 200, 100);

    /* Clear screen */
    fill_rect(0, 0, xres, yres, bg);

    /* Title bar */
    fill_rect(0, 0, xres, 40, title_bg);
    draw_string(10, 12, "SPEAr600 Linux", rgb565(255,255,255), title_bg, 2);

    /* System info */
    y = 60;

    /* Kernel */
    read_line("/proc/version", buf, sizeof(buf));
    buf[60] = 0; /* truncate */
    draw_string(10, y, "KERNEL:", accent, bg, 2);
    y += 20;
    draw_string(10, y, buf, text_fg, bg, 1);
    y += 20;

    /* CPU */
    f = fopen("/proc/cpuinfo", "r");
    if (f) {
        while (fgets(buf, sizeof(buf), f)) {
            if (strstr(buf, "Processor")) {
                buf[strcspn(buf, "\n")] = 0;
                draw_string(10, y, "CPU:", accent, bg, 2);
                y += 20;
                char *p = strchr(buf, ':');
                draw_string(10, y, p ? p+2 : buf, text_fg, bg, 1);
                y += 20;
                break;
            }
        }
        fclose(f);
    }

    /* Memory */
    f = fopen("/proc/meminfo", "r");
    if (f) {
        int total = 0, free_m = 0;
        while (fgets(buf, sizeof(buf), f)) {
            if (strstr(buf, "MemTotal")) sscanf(buf, "MemTotal: %d", &total);
            if (strstr(buf, "MemFree")) { sscanf(buf, "MemFree: %d", &free_m); break; }
        }
        fclose(f);
        draw_string(10, y, "MEMORY:", accent, bg, 2);
        y += 20;
        snprintf(buf, sizeof(buf), "Total: %dMB  Free: %dMB  Used: %dMB",
                total/1024, free_m/1024, (total-free_m)/1024);
        draw_string(10, y, buf, text_fg, bg, 1);
        y += 20;

        /* Memory bar */
        int bar_w = xres - 20;
        int used_w = bar_w * (total - free_m) / total;
        fill_rect(10, y, bar_w, 16, rgb565(60,60,80));
        fill_rect(10, y, used_w, 16, accent);
        y += 26;
    }

    /* Network */
    draw_string(10, y, "NETWORK:", accent, bg, 2);
    y += 20;
    f = popen("ifconfig eth0 2>/dev/null | grep 'inet addr'", "r");
    if (f) {
        if (fgets(buf, sizeof(buf), f)) {
            buf[strcspn(buf, "\n")] = 0;
            /* trim leading spaces */
            char *p = buf;
            while (*p == ' ') p++;
            draw_string(10, y, p, text_fg, bg, 1);
        }
        pclose(f);
    }
    y += 20;

    /* Uptime */
    draw_string(10, y, "UPTIME:", accent, bg, 2);
    y += 20;
    f = fopen("/proc/uptime", "r");
    if (f) {
        float up;
        fscanf(f, "%f", &up);
        fclose(f);
        int h = (int)up / 3600, m = ((int)up % 3600) / 60, s = (int)up % 60;
        snprintf(buf, sizeof(buf), "%02d:%02d:%02d", h, m, s);
        draw_string(10, y, buf, text_fg, bg, 1);
        y += 30;
    }

    /* Footer */
    fill_rect(0, yres - 30, xres, 30, title_bg);
    draw_string(10, yres - 22, "telnet 192.168.1.200 | Serial: ttyS0 115200", rgb565(200,200,200), title_bg, 1);

    munmap(fb_mem, finfo.smem_len);
    close(fb_fd);
    return 0;
}
