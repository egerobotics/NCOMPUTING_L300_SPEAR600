static int term_cols, term_rows;
static int cur_col, cur_row;
static int master_fd;
static int fifo_fd = -1;
static int kbd_fds[MAX_KBD_DEVS];
static int kbd_count = 0;
static int kbd_shift = 0;
static int kbd_ctrl = 0;
static pid_t child_pid;

/* Colors: RGB */
static unsigned char fg_r = 0, fg_g = 255, fg_b = 0;   /* green */
static unsigned char bg_r = 0, bg_g = 0, bg_b = 0;     /* black */

static void fb_putpixel(int x, int y, unsigned char r, unsigned char g, unsigned char b)
{
	unsigned char *p;
	if (x < 0 || x >= fb_width || y < 0 || y >= fb_height)
		return;
	p = fb_mem + y * fb_stride + x * fb_bpp;
	p[0] = r;
	p[1] = g;
	p[2] = b;
}

static void fb_fillrect(int x, int y, int w, int h,
			 unsigned char r, unsigned char g, unsigned char b)
{
	int i, j;
	for (j = y; j < y + h && j < fb_height; j++) {
		unsigned char *row = fb_mem + j * fb_stride + x * fb_bpp;
		for (i = 0; i < w && (x + i) < fb_width; i++) {
			row[i * fb_bpp] = r;
			row[i * fb_bpp + 1] = g;
			row[i * fb_bpp + 2] = b;
		}
	}
}

static void draw_char(int col, int row, unsigned char ch)
{
	int cx = col * 8;
	int cy = row * 16;
	int i, j;
	const unsigned char *glyph;

	if (ch < 32 || ch > 126)
		ch = 32;
	glyph = font8x16[ch - 32];

	for (j = 0; j < 16; j++) {
		unsigned char bits = glyph[j];
		unsigned char *p = fb_mem + (cy + j) * fb_stride + cx * fb_bpp;
		if (cy + j >= fb_height) break;
		for (i = 0; i < 8; i++) {
			if (cx + i >= fb_width) break;
			if (bits & (0x80 >> i)) {
				p[0] = fg_r; p[1] = fg_g; p[2] = fg_b;
			} else {
				p[0] = bg_r; p[1] = bg_g; p[2] = bg_b;
			}
			p += fb_bpp;
		}
	}
}

static void draw_cursor(void)
{
	int cx = cur_col * 8;
	int cy = cur_row * 16 + 14;
	fb_fillrect(cx, cy, 8, 2, fg_r, fg_g, fg_b);
}

static void clear_cursor(void)
{
	int cx = cur_col * 8;
	int cy = cur_row * 16 + 14;
	fb_fillrect(cx, cy, 8, 2, bg_r, bg_g, bg_b);
}

static void scroll_up(void)
{
	/* Copy framebuffer up by 16 pixels */
	int y;
	for (y = 0; y < (term_rows - 1) * 16; y++) {
		memcpy(fb_mem + y * fb_stride,
		       fb_mem + (y + 16) * fb_stride,
		       fb_width * fb_bpp);
	}
	/* Clear last line */
	fb_fillrect(0, (term_rows - 1) * 16, fb_width, 16, bg_r, bg_g, bg_b);
}

static void term_putchar(unsigned char c)
{
	clear_cursor();

	if (c == '\n') {
		cur_col = 0;
		cur_row++;
		if (cur_row >= term_rows) {
			scroll_up();
			cur_row = term_rows - 1;
		}
		draw_cursor();
		return;
	}
	if (c == '\r') {
		cur_col = 0;
		draw_cursor();
		return;
	}
	if (c == '\b' || c == 127) {
		if (cur_col > 0) {
			cur_col--;
			draw_char(cur_col, cur_row, ' ');
		}
		draw_cursor();
		return;
	}
	if (c == '\t') {
		int spaces = 8 - (cur_col % 8);
		int i;
		for (i = 0; i < spaces; i++) {
			draw_char(cur_col, cur_row, ' ');
			cur_col++;
			if (cur_col >= term_cols) {
				cur_col = 0;
				cur_row++;
				if (cur_row >= term_rows) {
					scroll_up();
					cur_row = term_rows - 1;
				}
			}
		}
		draw_cursor();
		return;
	}
	if (c < 32)
		return;

	draw_char(cur_col, cur_row, c);
	cur_col++;
	if (cur_col >= term_cols) {
		cur_col = 0;
		cur_row++;
		if (cur_row >= term_rows) {
			scroll_up();
			cur_row = term_rows - 1;
		}
	}
	draw_cursor();
}

static void term_write(const unsigned char *buf, int len)
{
	int i;
	static int in_esc = 0;
	static int in_bracket = 0;

	for (i = 0; i < len; i++) {
		if (in_esc) {
			if (buf[i] == '[') {
				in_bracket = 1;
				continue;
			}
			if (in_bracket) {
				if ((buf[i] >= 'A' && buf[i] <= 'Z') ||
				    (buf[i] >= 'a' && buf[i] <= 'z') ||
				    buf[i] == '@' || buf[i] == '~') {
					in_esc = 0;
					in_bracket = 0;

					/* Handle clear screen: ESC[2J or ESC[H */
					if (buf[i] == 'J') {
						fb_fillrect(0, 0, fb_width, fb_height,
							    bg_r, bg_g, bg_b);
						cur_col = 0;
						cur_row = 0;
					}
				}
				continue;
			}
			in_esc = 0;
			continue;
		}
		if (buf[i] == '\033') {
			in_esc = 1;
			in_bracket = 0;
			continue;
		}
		term_putchar(buf[i]);
	}
}

static int setup_pty(void)
{
	int master, slave;
	char slave_name[64];

	/* Try old-style BSD PTY */
	master = open("/dev/ptyp0", O_RDWR);
	if (master >= 0) {
		slave = open("/dev/ttyp0", O_RDWR);
		if (slave < 0) {
			close(master);
			return -1;
		}
	} else {
		/* Try Unix98 PTY */
		master = open("/dev/ptmx", O_RDWR | O_NOCTTY);
		if (master < 0) {
			perror("open pty");
			return -1;
		}
		grantpt(master);
		unlockpt(master);
		strncpy(slave_name, (char *)ptsname(master), sizeof(slave_name) - 1);
		slave = open(slave_name, O_RDWR);
		if (slave < 0) {
			close(master);
			return -1;
		}
	}

	child_pid = fork();
	if (child_pid < 0) {
		perror("fork");
		return -1;
	}

	if (child_pid == 0) {
		close(master);
		setsid();
		dup2(slave, 0);
		dup2(slave, 1);
		dup2(slave, 2);
		if (slave > 2)
			close(slave);

		setenv("TERM", "dumb", 1);
		setenv("USER", "root", 1);
		setenv("HOME", "/", 1);
		setenv("PS1", "# ", 1);
		setenv("PATH", "/bin:/sbin:/usr/bin:/usr/sbin:/usr/local/bin", 1);

		execl("/bin/sh", "sh", NULL);
		_exit(1);
	}

	close(slave);
	master_fd = master;
	return 0;
}

static int fb_open(void)
{
	struct fb_var_screeninfo vinfo;
	struct fb_fix_screeninfo finfo;

	fb_fd = open("/dev/fb0", O_RDWR);
	if (fb_fd < 0) {
		perror("open /dev/fb0");
		return -1;
	}

	ioctl(fb_fd, FBIOGET_VSCREENINFO, &vinfo);
	ioctl(fb_fd, FBIOGET_FSCREENINFO, &finfo);

	fb_width = vinfo.xres;
	fb_height = vinfo.yres;
	fb_bpp = vinfo.bits_per_pixel / 8;
	fb_stride = finfo.line_length;

	fb_mem = mmap(NULL, fb_stride * fb_height, PROT_READ | PROT_WRITE,
		      MAP_SHARED, fb_fd, 0);
	if (fb_mem == MAP_FAILED) {
		perror("mmap fb");
		return -1;
	}

	term_cols = fb_width / 8;
	term_rows = fb_height / 16;

	return 0;
}

static void open_input_keyboards(void)
{
	int i;
	char path[64];
	for (i = 0; i < 16 && kbd_count < MAX_KBD_DEVS; i++) {
		sprintf(path, "/dev/event%d", i);
		int fd = open(path, O_RDONLY | O_NONBLOCK);
		if (fd >= 0) {
			kbd_fds[kbd_count++] = fd;
			fprintf(stderr, "fbterm: opened %s\n", path);
		}
	}
	if (kbd_count == 0)
		fprintf(stderr, "fbterm: no input devices found\n");
}

static void handle_input_event(struct input_event *ev)
{
	if (ev->type != EV_KEY) return;

	/* Track modifier state */
	if (ev->code == KEY_LEFTSHIFT || ev->code == KEY_RIGHTSHIFT) {
		kbd_shift = (ev->value != 0);
		return;
	}
	if (ev->code == KEY_LEFTCTRL || ev->code == KEY_RIGHTCTRL) {
		kbd_ctrl = (ev->value != 0);
		return;
	}

	/* Only handle key press (value=1) and repeat (value=2) */
	if (ev->value == 0) return;

	/* Arrow keys -> ANSI escape sequences */
	if (ev->code == KEY_UP)    { write(master_fd, "\033[A", 3); return; }
	if (ev->code == KEY_DOWN)  { write(master_fd, "\033[B", 3); return; }
	if (ev->code == KEY_RIGHT) { write(master_fd, "\033[C", 3); return; }
	if (ev->code == KEY_LEFT)  { write(master_fd, "\033[D", 3); return; }
	if (ev->code == KEY_HOME)  { write(master_fd, "\033[H", 3); return; }
	if (ev->code == KEY_END)   { write(master_fd, "\033[F", 3); return; }
	if (ev->code == KEY_DELETE){ write(master_fd, "\033[3~", 4); return; }

	if (ev->code < 128) {
		char c = kbd_shift ? keymap_upper[ev->code] : keymap_lower[ev->code];
		if (c) {
			if (kbd_ctrl && c >= 'a' && c <= 'z')
				c = c - 'a' + 1; /* Ctrl+A=1, Ctrl+C=3, etc. */
			else if (kbd_ctrl && c >= 'A' && c <= 'Z')
				c = c - 'A' + 1;
			write(master_fd, &c, 1);
		}
	}
}

static volatile int running = 1;

static void sigchld(int sig)
{
	running = 0;
}

int main(void)
{
	struct termios old_tio, new_tio;

	signal(SIGCHLD, sigchld);
	signal(SIGPIPE, SIG_IGN);
	signal(SIGTTOU, SIG_IGN);
	signal(SIGTTIN, SIG_IGN);

	if (fb_open() < 0)
		return 1;

	fprintf(stderr, "fbterm: %dx%d framebuffer, %dx%d chars\n",
		fb_width, fb_height, term_cols, term_rows);

	/* Clear screen */
	fb_fillrect(0, 0, fb_width, fb_height, bg_r, bg_g, bg_b);

	if (setup_pty() < 0)
		return 1;

	/* Set stdin to raw mode if it's a terminal */
	int use_stdin = isatty(0);
	if (use_stdin) {
		tcgetattr(0, &old_tio);
		new_tio = old_tio;
		new_tio.c_lflag &= ~(ICANON | ECHO);
		new_tio.c_cc[VMIN] = 1;
		new_tio.c_cc[VTIME] = 0;
		tcsetattr(0, TCSANOW, &new_tio);
	}

	/* Open keyboard FIFO for VNC input */
	unlink(KBD_FIFO);
	mkfifo(KBD_FIFO, 0666);
	fifo_fd = open(KBD_FIFO, O_RDONLY | O_NONBLOCK);
	if (fifo_fd >= 0)
		fprintf(stderr, "fbterm: listening on %s for VNC keyboard\n", KBD_FIFO);

	/* Open USB keyboard input devices */
	open_input_keyboards();

	draw_cursor();

	while (running) {
		fd_set rfds;
		int maxfd, ret, k;
		struct timeval tv;

		FD_ZERO(&rfds);
		FD_SET(master_fd, &rfds);
		if (use_stdin) FD_SET(0, &rfds);
		maxfd = master_fd > 0 ? master_fd : 0;
		if (fifo_fd >= 0) {
			FD_SET(fifo_fd, &rfds);
			if (fifo_fd > maxfd) maxfd = fifo_fd;
		}
		for (k = 0; k < kbd_count; k++) {
			FD_SET(kbd_fds[k], &rfds);
			if (kbd_fds[k] > maxfd) maxfd = kbd_fds[k];
		}

		tv.tv_sec = 0;
		tv.tv_usec = 50000; /* 50ms */

		ret = select(maxfd + 1, &rfds, NULL, NULL, &tv);
		if (ret < 0) {
			if (errno == EINTR)
				continue;
			break;
		}

		/* Shell output -> framebuffer */
		if (FD_ISSET(master_fd, &rfds)) {
			unsigned char buf[512];
			int n = read(master_fd, buf, sizeof(buf));
			if (n <= 0) break;
			term_write(buf, n);
		}

		/* Console keyboard -> shell stdin */
		if (use_stdin && FD_ISSET(0, &rfds)) {
			unsigned char buf[64];
			int n = read(0, buf, sizeof(buf));
			if (n <= 0) break;
			write(master_fd, buf, n);
		}

		/* VNC keyboard (FIFO) -> shell stdin */
		if (fifo_fd >= 0 && FD_ISSET(fifo_fd, &rfds)) {
			unsigned char buf[64];
			int n = read(fifo_fd, buf, sizeof(buf));
			if (n > 0) {
				write(master_fd, buf, n);
			} else if (n == 0) {
				/* Writer closed, reopen FIFO */
				close(fifo_fd);
				fifo_fd = open(KBD_FIFO, O_RDONLY | O_NONBLOCK);
			}
		}

		/* USB keyboard input events -> shell stdin */
		for (k = 0; k < kbd_count; k++) {
			if (FD_ISSET(kbd_fds[k], &rfds)) {
				struct input_event ev;
				while (read(kbd_fds[k], &ev, sizeof(ev)) == sizeof(ev)) {
					handle_input_event(&ev);
				}
			}
		}
	}

	if (use_stdin)
		tcsetattr(0, TCSANOW, &old_tio);

	if (child_pid > 0) {
		kill(child_pid, SIGTERM);
		waitpid(child_pid, NULL, 0);
	}

	munmap(fb_mem, fb_stride * fb_height);
	close(fb_fd);

	return 0;
}
